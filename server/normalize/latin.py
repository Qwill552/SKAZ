"""Латиница. Обе модели Silero её не читают вовсе — непонятные модели
символы молча выбрасываются из входа, не заменяются пробелом (проверено
прямым вызовом `prepare_text_input` на `v5_ru.pt`: whitelist символов —
только строчная кириллица, `!+,-.:;?–…` и пробел; ни одной латинской
буквы). Из-за этого решение §4 исходного ТЗ ("оставляем как есть, Silero
прочтёт по русским правилам") расходится с фактическим поведением модели
— и уже отменено таблицей решений `skaz.md` ("Многоязычность": "латиницу
обе русские модели всё равно выбрасывают — её транслитерирует TTS-4").
Здесь — практическая транскрипция, не эстетика: тот же принцип, что у
чисел, — приблизительно правильно звучит лучше, чем беззвучно исчезает.

Порядок внутри слова: словарь исключений → аббревиатура из ЗАГЛАВНЫХ
побуквенно → общая транскрипция диграфами и одиночными буквами.
"""
import re

from .spans import sub

# Аббревиатура из заглавных — побуквенно. Стандартный русский вариант
# чтения латинских имён букв (как в "эйч-ти-эм-эль").
LETTERS = {
    "a": "эй", "b": "би", "c": "си", "d": "ди", "e": "и", "f": "эф",
    "g": "джи", "h": "эйч", "i": "ай", "j": "джей", "k": "кей", "l": "эль",
    "m": "эм", "n": "эн", "o": "оу", "p": "пи", "q": "кью", "r": "ар",
    "s": "эс", "t": "ти", "u": "ю", "v": "ви", "w": "дабл-ю", "x": "икс",
    "y": "вай", "z": "зет",
}

# Частые слова и смешанные аббревиатуры — словарь исключений, заводится
# по мере обнаружения (§4), не претендует на полноту.
EXCEPTIONS = {
    "google": "гугл",
    "windows": "виндоус",
    "wi-fi": "вай-фай",
    "mp3": "эм-пи-три",
    "youtube": "ютуб",
    "iphone": "айфон",
    "android": "андроид",
    "linux": "линукс",
    "python": "питон",
    "github": "гитхаб",
    "html": "эйч-ти-эм-эль",
    "css": "си-эс-эс",
    "usb": "юсб",
    "pdf": "пи-ди-эф",
    "ok": "окей",
}

# Практическая транскрипция слов вне словаря исключений — приближённая,
# не заменяет собой словарь. Диграфы длиннее одной буквы, поэтому
# проверяются раньше однобуквенных соответствий.
_DIGRAPHS = [
    ("tion", "шн"), ("sion", "жн"),
    ("th", "з"), ("sh", "ш"), ("ch", "ч"), ("ph", "ф"), ("ck", "к"),
    ("qu", "кв"), ("ng", "нг"), ("oo", "у"), ("ee", "и"), ("ea", "и"),
    ("ay", "эй"), ("ey", "эй"), ("oy", "ой"), ("ai", "эй"),
]
_SINGLE = {
    "a": "а", "b": "б", "c": "к", "d": "д", "e": "е", "f": "ф", "g": "г",
    "h": "х", "i": "и", "j": "дж", "k": "к", "l": "л", "m": "м", "n": "н",
    "o": "о", "p": "п", "q": "к", "r": "р", "s": "с", "t": "т", "u": "а",
    "v": "в", "w": "в", "x": "кс", "y": "й", "z": "з",
}

_WORD = re.compile(r"[A-Za-z][A-Za-z0-9-]*")


def _spell_acronym(word: str) -> str:
    return "-".join(LETTERS[c] for c in word.lower())


def _transcribe(word: str) -> str:
    result = []
    i = 0
    lower = word.lower()
    while i < len(lower):
        for digraph, sound in _DIGRAPHS:
            if lower.startswith(digraph, i):
                result.append(sound)
                i += len(digraph)
                break
        else:
            result.append(_SINGLE.get(lower[i], ""))
            i += 1
    return "".join(result)


def _replace(m: re.Match) -> str:
    word = m.group(0)
    lower = word.lower()

    if lower in EXCEPTIONS:
        return EXCEPTIONS[lower]

    letters_only = word.replace("-", "")
    if letters_only.isupper() and letters_only.isalpha():
        return _spell_acronym(letters_only)

    if "-" in word or any(c.isdigit() for c in word):
        # Смешанное (Wi-Fi, MP3) без записи в исключениях — транскрипция
        # применяется по буквенным кускам, цифры не трогаем: их к этому
        # моменту уже некому обработать (numbers.py прошёл раньше и
        # нарочно обходит цифры, слепленные с латиницей, см. numbers.py).
        return "".join(
            _transcribe(part) if part.isalpha() else part
            for part in re.split(r"(\d+)", word)
        )

    return _transcribe(word)


def transliterate_latin(text: str) -> str:
    return sub(_WORD, _replace, text)
