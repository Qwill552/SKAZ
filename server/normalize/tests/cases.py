def run() -> bool:
    failed = 0
    for description, raw, expected, user_dict in CASES:
        actual = normalize(raw, user_dict)
        ok = actual == expected
        status = "ok  " if ok else "FAIL"
        print(f"[{status}] {description}")
        if not ok:
            failed += 1
            print(f"       вход:     {raw!r}")
            print(f"       ожидали:  {expected!r}")
            print(f"       получили: {actual!r}")
    total = len(CASES)
    print(f"\n{total - failed}/{total} прошли.")
    return failed == 0


if __name__ == "__main__":
    sys.exit(0 if run() else 1)
